package dev.coala.demo;

import dev.coala.core.memory.InMemoryLongTermMemory;
import dev.coala.core.memory.MemoryRecord;
import dev.coala.core.memory.MemoryType;

import java.time.Duration;
import java.util.Iterator;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.NoSuchElementException;
import java.util.UUID;
import java.util.regex.Pattern;

/**
 * Bounded in-memory long-term memory sessions for the demo HTTP application.
 * Session IDs are server-generated unguessable capabilities for resuming demo memory,
 * but they are not a substitute for user authentication or authorization.
 */
public final class SessionMemoryStore {
    private static final Pattern SAFE_SESSION_ID = Pattern.compile("[A-Za-z0-9._-]{1,64}");
    private final int maxSessions;
    private final long idleTtlNanos;
    private final int maxRecordsPerSession;
    private final LinkedHashMap<String, Entry> sessions = new LinkedHashMap<>(16, 0.75f, true);

    public SessionMemoryStore(int maxSessions, Duration idleTtl) {
        this(maxSessions, idleTtl, InMemoryLongTermMemory.DEFAULT_MAX_RECORDS);
    }

    public SessionMemoryStore(int maxSessions, Duration idleTtl, int maxRecordsPerSession) {
        if (maxSessions < 1) throw new IllegalArgumentException("maxSessions must be positive");
        if (idleTtl == null || idleTtl.isZero() || idleTtl.isNegative()) {
            throw new IllegalArgumentException("idleTtl must be positive");
        }
        this.maxSessions = maxSessions;
        if (maxRecordsPerSession < 3) throw new IllegalArgumentException("maxRecordsPerSession must be at least 3 to retain demo seed memories");
        this.idleTtlNanos = idleTtl.toNanos();
        this.maxRecordsPerSession = maxRecordsPerSession;
    }

    /** Creates a server-generated opaque session when no ID is supplied; otherwise resumes an existing session. */
    public synchronized Session acquire(String requestedSessionId) {
        if (requestedSessionId == null || requestedSessionId.isBlank()) return createSession();

        String sessionId = requestedSessionId.trim();
        if (!SAFE_SESSION_ID.matcher(sessionId).matches()) {
            throw new IllegalArgumentException("sessionId must be 1-64 characters using letters, digits, '.', '_' or '-'.");
        }

        long now = System.nanoTime();
        evictExpired(now);
        Entry entry = sessions.get(sessionId);
        if (entry == null) {
            throw new NoSuchElementException("Session not found or expired. Start a new session without providing a sessionId.");
        }
        entry.lastAccessNanos = now;
        return new Session(sessionId, entry.memory);
    }

    /** Creates a new session ID generated by the server; callers cannot choose or reserve an ID. */
    public synchronized Session createSession() {
        long now = System.nanoTime();
        evictExpired(now);
        String sessionId;
        do {
            sessionId = UUID.randomUUID().toString();
        } while (sessions.containsKey(sessionId));
        Entry entry = new Entry(createSeededMemory(), now);
        sessions.put(sessionId, entry);
        evictExcessSessions();
        return new Session(sessionId, entry.memory);
    }

    public synchronized int activeSessionCount() {
        evictExpired(System.nanoTime());
        return sessions.size();
    }

    private void evictExpired(long now) {
        Iterator<Map.Entry<String, Entry>> iterator = sessions.entrySet().iterator();
        while (iterator.hasNext()) {
            Entry entry = iterator.next().getValue();
            if (now - entry.lastAccessNanos >= idleTtlNanos) iterator.remove();
        }
    }

    private void evictExcessSessions() {
        Iterator<Map.Entry<String, Entry>> iterator = sessions.entrySet().iterator();
        while (sessions.size() > maxSessions && iterator.hasNext()) {
            iterator.next();
            iterator.remove(); // LRU eviction; in-flight runs retain their local memory reference.
        }
    }

    private InMemoryLongTermMemory createSeededMemory() {
        InMemoryLongTermMemory memory = new InMemoryLongTermMemory(maxRecordsPerSession);
        memory.store(MemoryRecord.of(MemoryType.SEMANTIC,
                "For code changes, inspect the repository state and use test feedback before reporting completion."));
        memory.store(MemoryRecord.of(MemoryType.EPISODIC,
                "Previous demo puzzle experience: inspect available clues before committing to a final answer."));
        memory.store(MemoryRecord.of(MemoryType.SEMANTIC,
                "The current mock puzzle asks for a color word and excludes red."));
        return memory;
    }

    public record Session(String sessionId, InMemoryLongTermMemory longTermMemory) {}

    private static final class Entry {
        private final InMemoryLongTermMemory memory;
        private long lastAccessNanos;

        private Entry(InMemoryLongTermMemory memory, long lastAccessNanos) {
            this.memory = memory;
            this.lastAccessNanos = lastAccessNanos;
        }
    }
}
